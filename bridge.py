RISK_MODELS = ("yield_shock", "credit_crisis", "bank_run")  # โมเดลฝั่งเสี่ยงต่อ EM flow
CAUTION_COMPOSITE = 60.0    # composite ≥ 60 → ระวัง
RISKOFF_COMPOSITE = 75.0    # composite ≥ 75 → ตึงตัว
CAUTION_MODEL = 50.0        # โมเดลเสี่ยงตัวใดตัวหนึ่ง ≥ 50 → ระวัง
RISKOFF_MODEL = 65.0        # โมเดลเสี่ยงตัวใดตัวหนึ่ง ≥ 65 → ตึงตัว
RISKOFF_PAIR = 50.0         # โมเดลเสี่ยง ≥ 50 พร้อมกัน ≥ 2 ตัว → ตึงตัว

OVERLAY_DISCLAIMER = (
    "Overlay เป็น 'วินัยคุมขนาดความเสี่ยง' จากบริบทโลก — ไม่ใช่สัญญาณซื้อขาย "
    "กติกาข้างต้นตั้งจากทิศทางหลักฐาน (VIX/Fed/เครดิต → flow ต่างชาติ) แต่ยัง"
    "ไม่ผ่านการ validate เชิงประจักษ์กับ SET จึงไม่ถูกผูกเข้า backtest อัตโนมัติ "
    "และความสัมพันธ์พังได้ในวิกฤตจริง")


def _ok(x) -> bool:
    return x is not None and not (isinstance(x, float) and math.isnan(x))


def overlay_state(composite: float, model_scores: dict) -> dict:
    """สภาวะ overlay จากฝั่ง Global -> {level 0/1/2, label, reasons, guidance}

    level 0 = ปกติ | 1 = ระวัง | 2 = ตึงตัว (กติกาดู constants ด้านบน)
    model_scores: {key: score} จาก models6.score_models
    """
    reasons, level = [], 0
    risk_hits = []
    for k in RISK_MODELS:
        v = model_scores.get(k)
        if _ok(v) and v >= CAUTION_MODEL:
            risk_hits.append((k, float(v)))

    if _ok(composite) and composite >= RISKOFF_COMPOSITE:
        level = 2
        reasons.append(f"Crisis composite {composite:.0f} ≥ {RISKOFF_COMPOSITE:.0f}")
    if any(v >= RISKOFF_MODEL for _, v in risk_hits):
        level = 2
        for k, v in risk_hits:
            if v >= RISKOFF_MODEL:
                reasons.append(f"โมเดล {k} = {v:.0f} ≥ {RISKOFF_MODEL:.0f}")
    if len(risk_hits) >= 2 and level < 2:
        level = 2
        reasons.append("โมเดลเสี่ยง ≥ " + f"{RISKOFF_PAIR:.0f}" + " พร้อมกัน "
                       + str(len(risk_hits)) + " ตัว: "
                       + ", ".join(f"{k} {v:.0f}" for k, v in risk_hits))
    if level == 0:
        if _ok(composite) and composite >= CAUTION_COMPOSITE:
            level = 1
            reasons.append(f"Crisis composite {composite:.0f} ≥ {CAUTION_COMPOSITE:.0f}")
        elif risk_hits:
            level = 1
            k, v = risk_hits[0]
            reasons.append(f"โมเดล {k} = {v:.0f} ≥ {CAUTION_MODEL:.0f}")

    labels = {0: "ปกติ 🟢", 1: "ระวัง 🟡", 2: "ตึงตัว 🔴"}
    guidance = {
        0: "บริบทโลกไม่กดดันเป็นพิเศษ — ใช้กระบวนการฝั่ง SET ตามปกติ",
        1: "บริบทโลกเริ่มตึง — วินัยที่สมเหตุผล: ไม่เพิ่มขนาดไม้ใหม่เกินแผน, "
           "ทบทวน stop ให้เป็นปัจจุบัน (ไม่ใช่คำสั่งขาย)",
        2: "บริบทโลก risk-off — วินัยที่สมเหตุผล: ลดขนาดไม้ใหม่/ชะลอการเพิ่มสถานะ "
           "เพราะแรงขายต่างชาติมักกดทั้งกระดาน (ไม่ใช่คำสั่งขายของเดิม)",
    }
    if not _ok(composite) and not model_scores:
        return {"level": None, "label": "ไม่มีข้อมูล Global",
                "reasons": ["ยังไม่ได้เชื่อมข้อมูลฝั่ง Global (FRED/Demo)"],
                "guidance": "overlay ปิดอยู่ — ฝั่ง SET ทำงานตามปกติ",
                "disclaimer": OVERLAY_DISCLAIMER}
    return {"level": level, "label": labels[level],
            "reasons": reasons or ["ตัวชี้วัด Global อยู่โซนสงบทั้งหมด"],
            "guidance": guidance[level], "disclaimer": OVERLAY_DISCLAIMER}


