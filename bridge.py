# 3) บริบทค่าเงินบาท (USD/THB จาก yfinance: ค่าขึ้น = บาทอ่อน)
# ---------------------------------------------------------------------------

def thb_context(usdthb_close: pd.Series) -> dict:
    s = pd.Series(usdthb_close).dropna()
    if len(s) < 70:
        return {"ok": False}
    last = float(s.iloc[-1])
    chg_1m = float(s.iloc[-1] / s.iloc[-21] - 1.0) * 100 if len(s) > 21 else float("nan")
    chg_3m = float(s.iloc[-1] / s.iloc[-63] - 1.0) * 100 if len(s) > 63 else float("nan")
    if _ok(chg_1m) and chg_1m >= 2.0:
        text = (f"บาทอ่อนเร็ว ({chg_1m:+.1f}%/เดือน) — ในอดีตมักมาพร้อมแรงขาย"
                "ต่างชาติระดับดัชนี (บริบท ไม่ใช่ timing)")
    elif _ok(chg_1m) and chg_1m <= -2.0:
        text = (f"บาทแข็งเร็ว ({chg_1m:+.1f}%/เดือน) — มักสอดคล้องเงินไหลเข้า "
                "(บริบท ไม่ใช่ timing)")
    else:
        text = "ค่าเงินบาทเคลื่อนไหวปกติ — ไม่มีนัยพิเศษต่อ flow"
    return {"ok": True, "last": last, "chg_1m": chg_1m, "chg_3m": chg_3m,
            "text": text}


